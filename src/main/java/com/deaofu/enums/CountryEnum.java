    /**
     * 根据国家代码查找枚举项。
     *
     * @param code ISO 3166-1 alpha-2 国家代码（小写，例如 {@code za}），{@code null} 或空白返回 {@code null}
     * @return 命中的枚举项；未匹配时返回 {@code null}
     */
    public static CountryEnum getByCode(String code) {
        if (StrUtil.isBlank(code)) {
            return null;
        }
        for (CountryEnum value : values()) {
            if (value.getCode().equals(code)) {
                return value;
            }
        }
        return null;
    }

    /**
     * 根据国家代码取中文显示名。
     *
     * @param code ISO 3166-1 alpha-2 国家代码（小写，例如 {@code za}）
     * @return 中文名；未匹配时返回 {@code null}
     */
    public static String getInfoByCode(String code) {
        CountryEnum value = getByCode(code);
        return value == null ? null : value.getName();
    }

    /**
     * 返回 {@code "中文名,X,Y"} 形式的字符串（中间用英文逗号隔开），
     * 便于日志输出、序列化与人工核对坐标。
     *
     * @return 形如 {@code "南非,690,361"} 的字符串
     */
    public String toCoordinateString() {
        return name + "," + x + "," + y;
    }

    /**
     * 列出全部国家（按枚举声明顺序，即 ISO 代码字母升序），
     * 返回不可变 List，避免外部修改。
     *
     * <p>典型用途：前端首次进入世界地图页时，一次性拉取全部国家用于高亮 / 选中 / 搜索。</p>
     *
     * @return 全部枚举项的不可变列表
     */
    public static List<CountryEnum> listAll() {
        return Collections.unmodifiableList(Arrays.stream(values()).collect(Collectors.toList()));
    }
